import { createHash } from "node:crypto";
import { createGitHubApi, type GitHubApi, type GitHubReviewEvent } from "./github-api.js";
import { logger } from "./utils/logger";
import { detectPlatform, parsePrUrl } from "./platform.js";
import { buildInlineComments } from "./inline-comments";
import { renderMarkdown, renderSummaryMarkdown } from "./render.js";
import type {
  ParsedPrUrl,
  PostCommentResult,
  ReviewFinding,
  ReviewOutput,
} from "./types.js";

export function getFindingFingerprint(
  finding: ReviewFinding,
): string {
  const path = finding.code_location.path;
  const title = finding.title.replace(/^\[P[0-3]\]\s*/, "").trim().toLowerCase();
  return createHash("sha256").update(`${path}\n${title}`).digest("hex");
}

